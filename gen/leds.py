"""Every LED on the boards: which driver channel, what colour, what it is for.

The one source of truth for the light show: the schematic wires each LED to its
channel from here, the placement puts it where `where` says, and the firmware's
led_map.h (generated by gen/firmware_leds.py) carries the same table with the
positions filled in from the placement.

The LP5036 has 36 constant-current outputs in 12 banks of three (OUT0-2 are bank
0, ...).  Each output has its own 8-bit colour register; each bank shares one 8-bit
brightness register; the chip turns their product into 12-bit PWM at 29 kHz, with a
logarithmic curve if asked.  So LEDs that fade together share a bank, and a bank's
three outputs differ only in their colour registers.

Colours:
  orange  XL-1608UOC-06 0603, 600-610 nm (C965800)
  amber5050  HL-AF-5060S22OC 5050 three-die orange, dice in parallel (C516304)
  violet  HL-A-3528S7VC-S1-13HL 3528, 400-410 nm (C516136)
  purple  GL0603PU01 0603 phosphor purple (C51933300)
"""

# (driver, channel) -> (name, colour, where)
LEDS = {}


def _add(driver, ch, name, colour, where):
    assert (driver, ch) not in LEDS, (driver, ch)
    LEDS[(driver, ch)] = (name, colour, where)


# ---- U3, the base board's LP5036 (I2C 0x30) --------------------------------------
# Banks 0-3: twelve stars on an arc across the sky, the quantum ghost's path, in
# order along the arc (star 0 at the left).
for i in range(12):
    _add("BASE", i, "STAR%d" % i, "violet", "sky arc, position %d of 12, left to right" % i)
# Bank 4: the three pumpkins' faces (one channel each, dice in parallel).
for i in range(3):
    _add("BASE", 12 + i, "PUMPKIN%d" % i, "amber5050", "pumpkin %d's face, left to right" % i)
# Bank 5: the owl perch's ring; bank 6: the cat's (three each, 120 degrees apart), so
# each ring swirls on its own when its familiar arrives.
for i in range(3):
    _add("BASE", 15 + i, "OWLRING%d" % i, "purple", "round the owl's perch, at %d degrees" % (120 * i))
for i in range(3):
    _add("BASE", 18 + i, "CATRING%d" % i, "purple", "round the cat's perch, at %d degrees" % (120 * i))
# Banks 7-8: will-o'-the-wisps along the hill, left to right (the tilt game).
for i in range(6):
    _add("BASE", 21 + i, "WISP%d" % i, "purple", "along the hill, left to right, %d of 6" % i)
# Banks 9-10: four more stars, scattered (not on the arc).
for i in range(4):
    _add("BASE", 27 + i, "STARX%d" % i, "violet", "scattered sky star %d" % i)
# OUT31-35 spare.

# ---- U101, the tree's LP5036 (I2C 0x32) -------------------------------------------
# Banks 0-2: three owls' eyes, left/right (each owl's two eyes in one bank, so they
# open together); OUT2, OUT5 and OUT8, each bank's third output, are unused.
for k, owl in enumerate("ABC"):
    _add("TREE", 3 * k + 0, "OWL%s_L" % owl, "orange", "owl %s, left eye" % owl)
    _add("TREE", 3 * k + 1, "OWL%s_R" % owl, "orange", "owl %s, right eye" % owl)
# Banks 3-4: six violet stars on the tree's sky.
for i in range(6):
    _add("TREE", 9 + i, "TSTAR%d" % i, "violet", "tree sky star %d" % i)
# Bank 11: the perch's two downlights onto the floating bat (on the perch's underside,
# reached through the tree-perch header).  The last outputs, so that their two lines
# leave the driver below everything else and reach the header without crossing.
_add("TREE", 33, "PERCH_DOWN0", "violet", "perch underside, left of the coil")
_add("TREE", 34, "PERCH_DOWN1", "violet", "perch underside, right of the coil")
# Banks 6-7: four purple wisps in the tree's branches (OUT18-21).
for i in range(4):
    _add("TREE", 18 + i, "TWISP%d" % i, "purple", "in the tree's branches %d" % i)

DRIVER_ADDR = {"BASE": 0x30, "TREE": 0x32}
